// Scans every GameLanguage.Get(...) call and writes Shared/LocalizationCatalog.g.cs, the template
// list GameLanguage uses to pre-fill a fresh language file at startup.
//
// Run after adding or changing localization calls:
//     dotnet run --project tools/LocalizationScan
//
// Optional arguments: <repository-root> <output-file>.
// This tool is not part of the build. A stale catalog only means new templates are missing from
// the initial table; they are still collected at runtime and saved to the language file.
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

var root = args.Length > 0 ? Path.GetFullPath(args[0]) : FindRoot();
var output = args.Length > 1 ? Path.GetFullPath(args[1]) : Path.Combine(root, "Shared", "LocalizationCatalog.g.cs");

var templates = new SortedSet<string>(StringComparer.Ordinal);

foreach (var file in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
{
    var relative = Path.GetRelativePath(root, file);
    if (relative.StartsWith("obj" + Path.DirectorySeparatorChar) || relative.Contains(Path.DirectorySeparatorChar + "obj" + Path.DirectorySeparatorChar)) continue;
    if (relative.StartsWith("bin" + Path.DirectorySeparatorChar) || relative.Contains(Path.DirectorySeparatorChar + "bin" + Path.DirectorySeparatorChar)) continue;
    if (relative.StartsWith("Tools" + Path.DirectorySeparatorChar)) continue;
    if (file.EndsWith("Language.cs") || file.EndsWith("LocalizationStore.cs") || file.EndsWith("LocalizationCatalog.g.cs")) continue;

    string text;
    try { text = File.ReadAllText(file); } catch { continue; }
    if (!text.Contains("GameLanguage.")) continue;

    var tree = CSharpSyntaxTree.ParseText(text, path: file);
    var rootNode = tree.GetRoot();

    foreach (var invocation in rootNode.DescendantNodes().OfType<InvocationExpressionSyntax>())
    {
        if (invocation.Expression is not MemberAccessExpressionSyntax member) continue;
        if (member.Expression is not IdentifierNameSyntax receiver || receiver.Identifier.Text != "GameLanguage") continue;

        var name = member.Name.Identifier.Text;
        var arguments = invocation.ArgumentList.Arguments;

        string? template = name switch
        {
            "Get" when arguments.Count >= 1 => FromExpression(arguments[0].Expression),
            _ => null
        };

        if (!string.IsNullOrEmpty(template)) templates.Add(template);
    }
}

Directory.CreateDirectory(Path.GetDirectoryName(output)!);

var builder = new StringBuilder();
builder.AppendLine("// <auto-generated />");
builder.AppendLine("// Generated by Tools/LocalizationScan. Run it after adding localization calls.");
builder.AppendLine("public static class LocalizationCatalog");
builder.AppendLine("{");
builder.AppendLine("    public static readonly string[] Templates =");
builder.AppendLine("    {");
foreach (var template in templates)
{
    builder.Append("        ").Append(SymbolDisplay.FormatLiteral(template, true)).AppendLine(",");
}
builder.AppendLine("    };");
builder.AppendLine("}");

File.WriteAllText(output, builder.ToString(), new UTF8Encoding(false));
Console.WriteLine($"scanned {templates.Count} templates -> {output}");

static string? FromExpression(ExpressionSyntax expression)
{
    if (expression is InterpolatedStringExpressionSyntax interpolated)
    {
        var builder = new StringBuilder();
        var index = 0;

        foreach (var content in interpolated.Contents)
        {
            switch (content)
            {
                case InterpolatedStringTextSyntax text:
                    builder.Append(text.TextToken.ValueText);
                    break;
                case InterpolationSyntax value:
                    builder.Append('{').Append(index++);
                    if (value.AlignmentClause != null) builder.Append(',').Append(value.AlignmentClause.Value.NormalizeWhitespace().ToFullString());
                    if (value.FormatClause != null) builder.Append(':').Append(value.FormatClause.FormatStringToken.ValueText);
                    builder.Append('}');
                    break;
            }
        }

        return builder.ToString();
    }

    if (expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression))
        return literal.Token.ValueText;

    return null;
}

static string FindRoot()
{
    var directory = new DirectoryInfo(AppContext.BaseDirectory);

    while (directory != null && !Directory.Exists(Path.Combine(directory.FullName, ".git")))
        directory = directory.Parent;

    return directory?.FullName ?? Directory.GetCurrentDirectory();
}
